"""Makes the bundled background-music loops from scratch (pure maths, no samples).
Because these tracks are generated by this script they are copyright-free (CC0) -
you can use them anywhere. Run:  python tools/make_music.py
"""
import wave, os
import numpy as np

SR = 44100
OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "music")

def note(n):  # MIDI number -> Hz
    return 440.0 * 2 ** ((n - 69) / 12)

def env(length, a=0.01, r=0.3):
    t = np.arange(length) / SR
    e = np.minimum(1, t / a) * np.exp(-t / r)
    return e

def pad(freqs, dur):
    t = np.arange(int(dur * SR)) / SR
    s = sum(np.sin(2 * np.pi * f * t) * 0.5 + np.sin(2 * np.pi * f * 1.003 * t) * 0.5 for f in freqs)
    s *= np.minimum(1, t / 0.6) * np.minimum(1, (dur - t) / 0.6)
    return s / len(freqs)

def pluck(f, dur, decay=0.35):
    n = int(dur * SR)
    t = np.arange(n) / SR
    s = (np.sin(2 * np.pi * f * t) + 0.3 * np.sin(4 * np.pi * f * t) + 0.1 * np.sin(6 * np.pi * f * t))
    return s * env(n, 0.005, decay)

def kick(dur=0.4):
    n = int(dur * SR); t = np.arange(n) / SR
    f = 110 * np.exp(-t * 18) + 40
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 7)

def hat(dur=0.08, rng=np.random.default_rng(1)):
    n = int(dur * SR)
    x = rng.standard_normal(n)
    x = np.diff(x, prepend=0)
    return x * np.exp(-np.arange(n) / SR * 60) * 0.25

def song(name, bpm, chords, arp_pattern, drums=True, bars=8, seed=0):
    beat = 60 / bpm
    bar = beat * 4
    total = int(bars * bar * SR) + SR
    L = np.zeros(total); R = np.zeros(total)
    rng = np.random.default_rng(seed)
    for b in range(bars):
        ch = chords[b % len(chords)]
        start = int(b * bar * SR)
        p = pad([note(n) for n in ch], bar) * 0.22
        L[start:start + len(p)] += p; R[start:start + len(p)] += p
        for i, step in enumerate(arp_pattern):
            if step is None:
                continue
            s = pluck(note(ch[step % len(ch)] + 12), beat * 1.5) * 0.18
            pos = start + int(i * beat / 2 * SR)
            pan = 0.35 + 0.3 * rng.random()
            seg = slice(pos, pos + len(s))
            L[seg] += s[: len(L[seg])] * (1 - pan); R[seg] += s[: len(R[seg])] * pan
        if drums:
            for q in range(4):
                pos = start + int(q * beat * SR)
                if q in (0, 2):
                    k = kick() * 0.5; L[pos:pos + len(k)] += k; R[pos:pos + len(k)] += k
                h = hat(); hp = pos + int(beat / 2 * SR)
                L[hp:hp + len(h)] += h * 0.6; R[hp:hp + len(h)] += h
    # simple warm low-pass + soft clip
    k = np.ones(6) / 6
    L = np.convolve(L, k, "same"); R = np.convolve(R, k, "same")
    mx = max(np.abs(L).max(), np.abs(R).max())
    L = np.tanh(L / mx * 1.2) * 0.8; R = np.tanh(R / mx * 1.2) * 0.8
    fade = int(SR * 1.5)
    L[-fade:] *= np.linspace(1, 0, fade); R[-fade:] *= np.linspace(1, 0, fade)
    data = (np.stack([L, R], 1) * 32767).astype(np.int16)
    os.makedirs(OUT, exist_ok=True)
    with wave.open(os.path.join(OUT, name), "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(data.tobytes())

if __name__ == "__main__":
    # Fmaj7 - Em7 - Dm7 - Cmaj7  (dreamy, "aesthetic")
    song("soft-glow.wav", 84, [[53, 57, 60, 64], [52, 55, 59, 62], [50, 53, 57, 60], [48, 52, 55, 59]],
         [0, 2, 1, 3, 2, 1, 3, None], drums=True, bars=12, seed=1)
    # Am9 - Fmaj7 - Cmaj7 - G6  (lo-fi)
    song("lofi-blush.wav", 76, [[57, 60, 64, 67], [53, 57, 60, 64], [48, 52, 55, 59], [55, 59, 62, 64]],
         [0, None, 2, 1, None, 3, 2, None], drums=True, bars=10, seed=2)
    # Dmaj7 - Bm7 - Gmaj7 - A  (bright, no drums)
    song("morning-light.wav", 96, [[50, 54, 57, 61], [47, 50, 54, 57], [43, 47, 50, 54], [45, 49, 52, 57]],
         [0, 1, 2, 3, 2, 1, 0, 2], drums=False, bars=12, seed=3)
    print("done")
